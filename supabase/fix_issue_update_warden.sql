-- 4. Robust update_issue_status RPC with updater name support
CREATE OR REPLACE FUNCTION public.update_issue_status(
  p_issue_id BIGINT,
  p_new_status TEXT,
  p_note TEXT DEFAULT '',
  p_updater_id UUID DEFAULT NULL,
  p_updater_name TEXT DEFAULT NULL
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_old_status TEXT;
  v_hostel_id BIGINT;
  v_org_id UUID;
  v_sanitized_status TEXT;
  v_note_text TEXT;
  v_updater_uuid UUID;
  v_updater_name TEXT;
BEGIN
  -- Find current issue
  SELECT status, hostel_id, org_id INTO v_old_status, v_hostel_id, v_org_id
  FROM public.issues
  WHERE id = p_issue_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Issue % not found', p_issue_id;
  END IF;

  -- Normalize status (e.g. 'IN PROGRESS' -> 'in_progress', 'Pending' -> 'pending')
  v_sanitized_status := lower(replace(trim(p_new_status), ' ', '_'));

  IF v_sanitized_status NOT IN ('pending', 'in_progress', 'waiting_for_workers', 'completed', 'resolved') THEN
    v_sanitized_status := 'in_progress';
  END IF;

  v_note_text := trim(coalesce(p_note, ''));
  IF v_note_text = '' THEN
    v_note_text := 'Status changed to ' || replace(v_sanitized_status, '_', ' ');
  END IF;

  -- Resolve updater uuid
  v_updater_uuid := coalesce(auth.uid(), p_updater_id);

  -- Resolve updater name
  IF p_updater_name IS NOT NULL AND trim(p_updater_name) != '' THEN
    v_updater_name := trim(p_updater_name);
  ELSE
    SELECT 
      CASE 
        WHEN trim(concat(first_name, ' ', coalesce(last_name, ''))) != '' THEN 
          concat(trim(concat(first_name, ' ', coalesce(last_name, ''))), CASE WHEN role IS NOT NULL AND trim(role) != '' THEN concat(' (', role, ')') ELSE '' END)
        WHEN email IS NOT NULL AND email != '' THEN 
          concat(email, CASE WHEN role IS NOT NULL AND trim(role) != '' THEN concat(' (', role, ')') ELSE '' END)
        ELSE NULL
      END INTO v_updater_name
    FROM public.profiles
    WHERE id = v_updater_uuid;
  END IF;

  -- Update issues table
  UPDATE public.issues
  SET status = v_sanitized_status,
      resolved_at = CASE WHEN v_sanitized_status IN ('completed', 'resolved') THEN NOW() ELSE NULL END,
      updated_at = NOW()
  WHERE id = p_issue_id;

  -- Insert history record into issue_updates
  INSERT INTO public.issue_updates (
    issue_id, old_status, new_status, note, updated_by, updated_by_name, org_id, created_at
  ) VALUES (
    p_issue_id,
    v_old_status,
    v_sanitized_status,
    v_note_text,
    v_updater_uuid,
    v_updater_name,
    coalesce(v_org_id, public.user_org_id(), '00000000-0000-0000-0000-000000000001'::uuid),
    NOW()
  );

  RETURN jsonb_build_object(
    'success', true,
    'issue_id', p_issue_id,
    'new_status', v_sanitized_status,
    'old_status', v_old_status,
    'updated_by_name', v_updater_name
  );
END;
$$;

REVOKE EXECUTE ON FUNCTION public.update_issue_status(BIGINT, TEXT, TEXT, UUID, TEXT) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.update_issue_status(BIGINT, TEXT, TEXT, UUID, TEXT) TO authenticated, anon, service_role;

