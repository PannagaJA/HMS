-- 1. Ensure issue_updates table columns and constraints are clean
CREATE TABLE IF NOT EXISTS public.issue_updates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    issue_id BIGINT NOT NULL REFERENCES public.issues(id) ON DELETE CASCADE,
    old_status TEXT,
    new_status TEXT NOT NULL,
    note TEXT,
    updated_by UUID REFERENCES public.profiles(id) ON DELETE SET NULL,
    updated_by_name TEXT,
    org_id UUID NOT NULL DEFAULT '00000000-0000-0000-0000-000000000001',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Add updated_by_name column if table already existed without it
ALTER TABLE public.issue_updates ADD COLUMN IF NOT EXISTS updated_by_name TEXT;

