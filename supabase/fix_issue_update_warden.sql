-- 7. Automatic backfill for existing issue_updates records missing updater name
UPDATE public.issue_updates iu
SET updated_by_name = CASE
  WHEN p.first_name IS NOT NULL AND trim(p.first_name) != '' THEN
    concat(trim(concat(p.first_name, ' ', coalesce(p.last_name, ''))), CASE WHEN p.role IS NOT NULL AND trim(p.role) != '' THEN concat(' (', p.role, ')') ELSE '' END)
  WHEN p.email IS NOT NULL AND trim(p.email) != '' THEN
    concat(p.email, CASE WHEN p.role IS NOT NULL AND trim(p.role) != '' THEN concat(' (', p.role, ')') ELSE '' END)
  ELSE NULL
END
FROM public.profiles p
WHERE iu.updated_by = p.id AND (iu.updated_by_name IS NULL OR trim(iu.updated_by_name) = '');

-- If updated_by was NULL on existing tickets, resolve from hostel's assigned warden or default warden profile
UPDATE public.issue_updates iu
SET updated_by_name = coalesce(
  (
    SELECT concat(trim(concat(p.first_name, ' ', coalesce(p.last_name, ''))), ' (', coalesce(p.role, 'Warden'), ')')
    FROM public.warden_hostel_assignments wha
    JOIN public.profiles p ON p.id = wha.warden_profile_id
    JOIN public.issues i ON i.id = iu.issue_id
    WHERE wha.hostel_id = i.hostel_id
    LIMIT 1
  ),
  (
    SELECT concat(trim(concat(first_name, ' ', coalesce(last_name, ''))), ' (', coalesce(role, 'Warden'), ')')
    FROM public.profiles
    WHERE role = 'WARDEN'
    LIMIT 1
  ),
  (
    SELECT concat(trim(name), ' (', coalesce(designation, 'Warden'), ')')
    FROM public.hostel_wardens
    LIMIT 1
  ),
  'Hostel Warden'
)
WHERE (iu.updated_by_name IS NULL OR trim(iu.updated_by_name) = '') AND iu.new_status != 'pending';
